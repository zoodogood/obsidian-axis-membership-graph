import esbuild from 'esbuild';
import { spawn } from 'node:child_process';
import { copyFile, mkdir } from 'node:fs/promises';
import { builtinModules } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'process';

const root = dirname(fileURLToPath(import.meta.url));

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

/** The build output directory. Its content is what gets deployed to the vault. */
const outDir = 'dist';

/** Static assets that Obsidian expects next to `main.js` in the plugin folder. */
const assets = ['manifest.json', 'styles.css'];

/**
 * Copies the static assets into the build output directory, so that `dist`
 * contains everything the plugin needs at runtime.
 */
const copyAssets = {
	name: 'copy-assets',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length > 0) return;
			await mkdir(join(root, outDir), { recursive: true });
			for (const asset of assets) {
				await copyFile(join(root, asset), join(root, outDir, asset));
			}
		});
	},
};

/**
 * Copies the built plugin into the local Obsidian vault.
 * Failures are reported but never break the build.
 */
const deployPlugin = {
	name: 'deploy-to-vault',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length > 0) return;
			await new Promise((resolvePromise) => {
				const child = spawn(process.execPath, [join(root, 'scripts', 'deploy.mjs')], {
					stdio: 'inherit',
				});
				child.on('close', (code) => {
					if (code !== 0) {
						console.warn('[deploy] Skipped: vault path is not configured or the vault is unreachable.');
					}
					resolvePromise();
				});
			});
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: join(outDir, 'main.js'),
	minify: prod,
	plugins: [copyAssets, deployPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
